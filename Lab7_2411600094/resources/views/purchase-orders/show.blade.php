@push('scripts')
    @php
        // Lab 6 modal-reopen pattern: a failed post sends the browser back to
        // this page with the modal already closed, which looks like the button
        // did nothing. Which modal to re-open follows from which field errored.
        $reopen = collect(['rejection_reason' => 'reject', 'cancellation_reason' => 'cancel'])
                    ->first(fn ($verb, $field) => $errors->has($field));

        if (! $reopen && ($errors->has('received') || $errors->has('received.*'))) {
            $reopen = 'receive';
        }
    @endphp

    <script>
        const poReopenModal = document.getElementById(@json($reopen ? "po-{$reopen}-{$order->id}" : null));

        if (poReopenModal) {
            document.addEventListener('DOMContentLoaded', () => new bootstrap.Modal(poReopenModal).show());
        }
    </script>
@endpush
